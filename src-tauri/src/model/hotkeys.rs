/// The declared action with this id.
pub fn find_action(id: &str) -> Option<&'static HotkeyActionDecl> {
    HOTKEY_ACTIONS.iter().find(|decl| decl.id == id)
}

/// The widget type a generated visibility action belongs to.
pub fn visibility_action_owner(id: &str) -> Option<&str> {
    id.strip_prefix(WIDGET_VISIBILITY_ACTION_PREFIX)?
        .strip_suffix(WIDGET_VISIBILITY_ACTION_SUFFIX)
        .filter(|owner| !owner.is_empty())
}

/// How the interact key behaves: a toggle, or on only while held.
#[cfg_attr(feature = "dev", derive(specta::Type))]
#[derive(Serialize, Deserialize, Debug, Clone, Copy, PartialEq, Eq, Default)]
#[serde(rename_all = "camelCase")]
pub enum InteractHotkeyMode {
    #[default]
    Toggle,
    Hold,
}

/// What the dispatcher needs from the main window's settings and layout,
/// pushed whenever any of it changes.
#[cfg_attr(feature = "dev", derive(specta::Type))]
#[derive(Serialize, Deserialize, Debug, Clone, PartialEq, Default)]
#[serde(rename_all = "camelCase")]
pub struct HotkeyContext {
    /// Widget types with at least one instance on screen in the live layout.
    /// A widget's actions fire only while it is listed here.
    pub widgets_on_screen: Vec<String>,
    pub interact_hotkey_mode: InteractHotkeyMode,
    /// Interact mode switches itself off after this long; 0 never does.
    pub interact_auto_off_seconds: f32,
}

/// The overlay's two mouse modes. Owned by the dispatcher, mirrored by every
/// window. Only one can be on: drag consumes pointer events on the container,
/// interact needs them to reach the widget content.
#[cfg_attr(feature = "dev", derive(specta::Type))]
#[derive(Serialize, Deserialize, Debug, Clone, Copy, PartialEq, Eq, Default)]
#[serde(rename_all = "camelCase")]
pub struct OverlayModes {
    pub drag_mode: bool,
    pub interact_mode: bool,
}

/// A settings action whose key fired, for the main window to apply.
#[cfg_attr(feature = "dev", derive(specta::Type))]
#[derive(Serialize, Deserialize, Debug, Clone, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct HotkeySettingsAction {
    pub action_id: String,
}

/// An action as the settings window lists it.
#[cfg_attr(feature = "dev", derive(specta::Type))]
#[derive(Serialize, Debug, Clone, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct HotkeyActionSpec {
    pub id: String,
    pub owner: String,
    pub label_key: String,
    pub kind: HotkeyKind,
    pub trigger: HotkeyTrigger,
    pub default_binding: Option<Binding>,
}

impl From<&HotkeyActionDecl> for HotkeyActionSpec {
    fn from(decl: &HotkeyActionDecl) -> Self {
        Self {
            id: decl.id.to_string(),
            owner: decl.owner.to_string(),
            label_key: decl.label_key.to_string(),
            kind: decl.effect.kind(),
            trigger: decl.effect.trigger(),
            default_binding: decl.default_key.map(|key| Binding::Keyboard {
                accelerator: key.to_string(),
            }),
        }
    }
}

/// Writes the action list as a TypeScript value, next to the other generated
/// value files.
#[cfg(feature = "dev")]
pub fn export_hotkey_actions(path: &str) -> std::io::Result<()> {
    use crate::model::ts_values::GENERATED_HEADER;

    let specs: Vec<HotkeyActionSpec> = HOTKEY_ACTIONS.iter().map(HotkeyActionSpec::from).collect();
    let list = serde_json::to_string_pretty(&specs).map_err(std::io::Error::other)?;

    let out = format!(
        "{GENERATED_HEADER}\n\n\
         import type {{ HotkeyActionSpec }} from '@/types/bindings';\n\n\
         /** Every bindable action but the generated per-widget visibility ones. */\n\
         export const HOTKEY_ACTIONS: readonly HotkeyActionSpec[] = {list};\n\n\
         /** `widget:<type>:toggle-visibility` — see `model/hotkeys.rs`. */\n\
         export const WIDGET_VISIBILITY_ACTION_PREFIX = {WIDGET_VISIBILITY_ACTION_PREFIX:?};\n\n\
         export const WIDGET_VISIBILITY_ACTION_SUFFIX = {WIDGET_VISIBILITY_ACTION_SUFFIX:?};\n"
    );

    std::fs::write(path, out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_action_id_is_unique() {
        for (index, decl) in HOTKEY_ACTIONS.iter().enumerate() {
            assert!(
                HOTKEY_ACTIONS[index + 1..]
                    .iter()
                    .all(|other| other.id != decl.id),
                "duplicate action id {}",
                decl.id
            );
        }
    }

    #[test]
    fn only_the_interact_key_is_held() {
        let held: Vec<&str> = HOTKEY_ACTIONS
            .iter()
            .filter(|decl| decl.effect.trigger() == HotkeyTrigger::Hold)
            .map(|decl| decl.id)
            .collect();

        assert_eq!(held, vec!["app:toggle-interact-mode"]);
    }

    #[test]
    fn reads_the_widget_off_a_visibility_action() {
        assert_eq!(
            visibility_action_owner("widget:track-map:toggle-visibility"),
            Some("track-map")
        );
        assert_eq!(visibility_action_owner("widget::toggle-visibility"), None);
        assert_eq!(visibility_action_owner("standings:scroll-up"), None);
    }

    #[test]
    fn a_binding_reads_the_shape_the_settings_file_stores() {
        let device: Binding =
            serde_json::from_str(r#"{"kind":"device","deviceId":"guid-1","button":4}"#).unwrap();
        let keyboard: Binding =
            serde_json::from_str(r#"{"kind":"keyboard","accelerator":"F9"}"#).unwrap();

        assert_eq!(
            device,
            Binding::Device {
                device_id: "guid-1".into(),
                button: 4
            }
        );
        assert_eq!(
            keyboard,
            Binding::Keyboard {
                accelerator: "F9".into()
            }
        );
    }

    /// The checked-in list carries every id and label the backend declares.
    /// Quote-blind like the other value files: `oxfmt` rewrites the quotes.
    #[cfg(feature = "dev")]
    #[test]
    fn the_checked_in_action_list_is_current() {
        let checked_in = std::fs::read_to_string(crate::bindings::HOTKEY_ACTIONS_PATH)
            .expect("hotkey-actions.ts is missing — regenerate with UPDATE_BINDINGS=1")
            .replace('\'', "\"");

        for decl in HOTKEY_ACTIONS {
            for value in [Some(decl.id), Some(decl.label_key), decl.default_key]
                .into_iter()
                .flatten()
            {
                assert!(
                    checked_in.contains(&format!("\"{value}\"")),
                    "hotkey-actions.ts is stale: `{value}` is missing.\n\
                     Rerun with UPDATE_BINDINGS=1 cargo test --features dev, then npm run format."
                );
            }
        }
    }
}
