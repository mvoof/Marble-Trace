//! The bindable actions, declared once, and the shapes the hotkey dispatcher
//! takes from and gives to the frontend.
//!
//! The list is a value, not a type: the settings window needs every id, label
//! and default binding as a literal, and the dispatcher needs to know what each
//! one does. Both read [`HOTKEY_ACTIONS`] — the frontend through the file
//! [`export_hotkey_actions`] writes. Adding an action is one entry here and
//! its label under `bindings.actions` in `main-app.json`.
//!
//! What an action *does* is its [`HotkeyEffect`], and the effect decides the
//! kind the frontend sees:
//!
//! - **sim** — acts on the car through the telemetry thread. Passes the layout
//!   gate and nothing else.
//! - **view** — a control message to the windows and remote screens that draw
//!   the widget, or the overlay's own drag and interact modes. Each client
//!   picks the instances marked for hotkeys itself.
//! - **settings** — writes settings, which the main window owns. The dispatcher
//!   catches the key and hands the action to main, which applies it.

// The labels, kinds and defaults are read only by the `dev` exporter that
// writes them out for the frontend; a release build would flag them unused.
#![cfg_attr(not(feature = "dev"), allow(dead_code))]

use serde::{Deserialize, Serialize};

use crate::model::pit_action::{PitAction, TireCorner};

/// Owner of the actions that are not a widget's. Never gated by the layout.
pub const APP_OWNER: &str = "app";

/// The per-widget show/hide action is generated by the frontend from its
/// widget catalog — the backend does not know the widgets — so it is
/// recognised by its shape: `widget:<type>:toggle-visibility`.
pub const WIDGET_VISIBILITY_ACTION_PREFIX: &str = "widget:";
pub const WIDGET_VISIBILITY_ACTION_SUFFIX: &str = ":toggle-visibility";

/// One press of a scroll key moves a block rather than a row — a key has no
/// inertia, so row-by-row stepping is too slow to be usable.
const SCROLL_STEP_ROWS: i32 = 3;

/// An input binding as it is stored and sent: a keyboard accelerator, or a
/// controller button addressed by the device's stable identity.
#[cfg_attr(feature = "dev", derive(specta::Type))]
#[derive(Serialize, Deserialize, Debug, Clone, PartialEq, Eq, Hash)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum Binding {
    Keyboard {
        /// Tauri accelerator, e.g. "Control+Shift+P".
        accelerator: String,
    },
    Device {
        /// Stable device identity, not an enumeration index. See
        /// `input::identity`.
        #[serde(rename = "deviceId")]
        device_id: String,
        button: u32,
    },
}

/// `press` runs once, on key down. `hold` runs on both edges with whether the
/// key is down — interact mode's hold variant.
#[cfg_attr(feature = "dev", derive(specta::Type))]
#[derive(Serialize, Deserialize, Debug, Clone, Copy, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub enum HotkeyTrigger {
    Press,
    Hold,
}

#[cfg_attr(feature = "dev", derive(specta::Type))]
#[derive(Serialize, Deserialize, Debug, Clone, Copy, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub enum HotkeyKind {
    Sim,
    View,
    Settings,
}

/// A control message for the windows drawing a widget. Sent as a step, never a
/// value: only the window an instance is mounted in holds its state.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ViewControl {
    /// One class forward (`1`) or back (`-1`).
    StandingsClassStep(i32),
    StandingsScroll(i32),
    /// Positive lifts the chat towards older messages.
    StreamChatScroll(i32),
    /// Pops the order box up away from the pit lane.
    PitServiceToggle,
}

/// What an action does when its key fires.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum HotkeyEffect {
    Pit(PitAction),
    /// Hands the stop to the driver, or back to auto mode.
    PitAutoMode,
    View(ViewControl),
    ToggleDragMode,
    /// Toggles, or follows the key while held — `interactHotkeyMode` decides.
    InteractMode,
    /// Applied by the main window.
    Settings,
}

impl HotkeyEffect {
    pub const fn kind(self) -> HotkeyKind {
        match self {
            Self::Pit(_) | Self::PitAutoMode => HotkeyKind::Sim,
            Self::View(_) | Self::ToggleDragMode | Self::InteractMode => HotkeyKind::View,
            Self::Settings => HotkeyKind::Settings,
        }
    }

    pub const fn trigger(self) -> HotkeyTrigger {
        match self {
            Self::InteractMode => HotkeyTrigger::Hold,
            _ => HotkeyTrigger::Press,
        }
    }
}

/// One bindable action.
#[derive(Debug, Clone, Copy)]
pub struct HotkeyActionDecl {
    /// Stable, persisted key. Never renamed once shipped.
    pub id: &'static str,
    /// Widget type that owns the action, or [`APP_OWNER`]. Drives the layout
    /// gate and the grouping in the settings.
    pub owner: &'static str,
    /// i18n key under `bindings.actions` in `main-app.json`.
    pub label_key: &'static str,
    /// Shipped keyboard default; `None` starts unbound.
    pub default_key: Option<&'static str>,
    pub effect: HotkeyEffect,
}

const fn action(
    id: &'static str,
    owner: &'static str,
    label_key: &'static str,
    effect: HotkeyEffect,
) -> HotkeyActionDecl {
    HotkeyActionDecl {
        id,
        owner,
        label_key,
        default_key: None,
        effect,
    }
}

const fn bound(decl: HotkeyActionDecl, key: &'static str) -> HotkeyActionDecl {
    HotkeyActionDecl {
        default_key: Some(key),
        ..decl
    }
}

const fn pit(id: &'static str, label_key: &'static str, pit_action: PitAction) -> HotkeyActionDecl {
    action(id, "pit-service", label_key, HotkeyEffect::Pit(pit_action))
}

const fn tire(id: &'static str, label_key: &'static str, corner: TireCorner) -> HotkeyActionDecl {
    pit(id, label_key, PitAction::ToggleTire { corner })
}

